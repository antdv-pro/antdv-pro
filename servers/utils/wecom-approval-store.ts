async function syncOneApproval(spNo: string, localInstanceId?: string) {
  if (!spNo.trim())
    throw new Error('请输入企业微信审批单号')
  const result = await requestWecom('/cgi-bin/oa/getapprovaldetail', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ sp_no: spNo.trim() }) })
  const detail = result.info || result
  const applicantId = String(detail.applyer?.userid || '').trim()
  if (!applicantId)
    throw new Error('审批发起人不属于当前企业组织')

  const value = state()
  const templateId = String(detail.template_id || 'unknown')
  const fields = approvalFields(detail)
  const contents = approvalContents(detail)
  const candidateMappings = value.mappings.filter(item => item.enabled
    && item.templateId === templateId
    && item.direction === 'WECOM_TO_CENTER')
  const searchableText = [detail.sp_name, ...fields.map(field => `${field.title}:${field.value}`)].filter(Boolean).join('；')
  const inferredBusinessType = inferApprovalBusinessType(searchableText)
  let mapping = inferredBusinessType
    ? candidateMappings.find(item => item.businessType === inferredBusinessType)
    : undefined
  if (!mapping && inferredBusinessType && APPROVAL_BUSINESS_MAP.has(inferredBusinessType)) {
    const base = candidateMappings[0]
    const catalog = APPROVAL_BUSINESS_MAP.get(inferredBusinessType)!
    mapping = {
      ...(base || {
        id: `AUTO-${templateId}`,
        templateId,
        templateName: String(detail.sp_name || catalog.label),
        direction: 'WECOM_TO_CENTER' as const,
        enabled: true,
        updatedAt: new Date().toISOString(),
      }),
      businessType: inferredBusinessType,
      businessLabel: catalog.label,
      autoGenerated: true,
    }
  }
  if (!mapping && candidateMappings.length === 1 && APPROVAL_BUSINESS_MAP.has(candidateMappings[0].businessType))
    mapping = candidateMappings[0]
  if (!mapping)
    throw new Error(`无法根据审批事项识别业务模块：${searchableText.slice(0, 120) || templateId}`)

  const fieldValue = (pattern: RegExp) => fields.find(field => pattern.test(field.title))?.value
  const amountValue = mapping.amountControlId ? contents.get(mapping.amountControlId) : fieldValue(/金额|款项|合计/)
  const amount = amountValue !== undefined && amountValue !== '' ? Number(amountValue) : undefined
  const status = mapStatus(detail.sp_status)
  const submittedAt = toIsoTime(detail.apply_time)
  const completedAt = latestApprovalTime(detail.sp_record)
  const applicant = await resolveWecomUser(applicantId)
  const departmentId = detail.applyer?.partyid || applicant.departmentIds[0]
  const departmentName = await resolveDepartmentName(departmentId)
  const boundUser = await systemStore.bindWecomIdentity({
    wecomUserId: applicantId,
    mobile: applicant.mobile,
    nickname: applicant.name,
    wecomDepartmentId: String(departmentId || ''),
    deptName: departmentName,
  })
  const localApplicantId = boundUser?.id ?? applicantId
  const localApplicantName = boundUser?.nickname || applicant.name
  const localDepartmentId = boundUser?.deptId || departmentId
  const localDepartmentName = boundUser?.deptName || departmentName
  const approvalFlow = await enrichApprovalFlow(detail.sp_record)
  const notifyers = await Promise.all((detail.notifyer || []).map(async (item: any) => {
    const userId = String(item.userid || item)
    return { userId, name: (await resolveWecomUser(userId)).name }
  }))
  const displayTitle = String((mapping.titleControlId && contents.get(mapping.titleControlId)) || detail.sp_name || mapping.businessLabel)
  const paymentDate = fieldValue(/付款日期/)
  const occurredDate = mapping.dateControlId
    ? contents.get(mapping.dateControlId)
    : fieldValue(/业务日期|发生日期|申请日期/) || fields.find(field => /^日期$|^业务时间$/.test(field.title))?.value
  const financialPeriod = resolveApprovalFinancialPeriod(
    [occurredDate, paymentDate, submittedAt],
    fieldValue(/财务年度|财务年/),
    fieldValue(/财务月份|财务月/),
  )
  const receivingAccount = fieldValue(/收款账户|收款账号/) as Record<string, any> | undefined
  const attachmentFiles = fieldValue(/付款凭证附件|附件/) as Array<Record<string, any>> | undefined
  const formData = {
    approvalType: mapping.businessLabel,
    category: mapping.autoGenerated ? '企业微信自动分类' : APPROVAL_BUSINESS_MAP.get(mapping.businessType)?.category,
    moduleName: mapping.autoGenerated ? '审批中心' : APPROVAL_BUSINESS_MAP.get(mapping.businessType)?.moduleName,
    modulePath: mapping.autoGenerated ? '/oa-approval/center' : APPROVAL_BUSINESS_MAP.get(mapping.businessType)?.modulePath,
    contentOption: mapping.expenseTypeControlId ? contents.get(mapping.expenseTypeControlId) : fieldValue(/类型|类别/),
    description: mapping.reasonControlId ? contents.get(mapping.reasonControlId) : fieldValue(/事由|用途|原因|说明/),
    occurredDate,
    paymentDate,
    paymentMethod: fieldValue(/付款方式/),
    receivingAccount,
    counterparty: receivingAccount?.accountName,
    payeeName: receivingAccount?.accountName,
    accountType: receivingAccount?.accountType,
    accountName: receivingAccount?.accountName,
    accountNumber: receivingAccount?.accountNumber,
    bankName: receivingAccount?.bankName,
    bankProvince: receivingAccount?.bankProvince,
    bankCity: receivingAccount?.bankCity,
    bankBranchName: receivingAccount?.bankBranchName,
    attachmentFiles,
    attachmentName: attachmentFiles?.map(file => file.name).join('、'),
    remark: mapping.remarkControlId ? contents.get(mapping.remarkControlId) : fieldValue(/备注/),
    ...financialPeriod,
    amount,
    businessDomain: resolveBusinessDomain(departmentName),
    departmentName: localDepartmentName,
    source: '企业微信',
    wecomSpNo: spNo,
    wecomTemplateId: templateId,
    wecomTemplateName: detail.sp_name || mapping.templateName,
    controls: fields,
    approvalFlow,
    notifyers,
    originalStatus: detail.sp_status,
  }
  const existingRecord = value.records.find(item => item.spNo === spNo)
  const record: WecomSyncRecord = {
    id: `WCS-${spNo}`,
    spNo,
    localInstanceId: localInstanceId || existingRecord?.localInstanceId,
    templateId,
    title: displayTitle,
    applicantName: applicant.name,
    status,
    source: 'WECOM',
    lastSyncedAt: new Date().toISOString(),
    message: '已从企业微信拉取最新状态',
  }

  if (mapping.autoGenerated) {
    const synced = await approvalStore.upsertExternal({
      externalKey: spNo,
      approvalType: mapping.businessLabel,
      businessType: mapping.businessType,
      businessNo: spNo,
      title: displayTitle,
      applicantId: localApplicantId,
      applicantName: localApplicantName,
      deptId: localDepartmentId,
      deptName: localDepartmentName,
      amount: Number.isFinite(amount) ? amount : undefined,
      status: status === 'UNKNOWN' ? 'APPROVING' : status,
      submittedAt,
      completedAt,
      formData,
      ccUserIds: notifyers.map(item => item.userId),
    })
    record.localInstanceId = synced.instance.id
  }
  else {
    if (!record.localInstanceId) {
      const submitted = await approvalStore.submit({
        businessType: mapping.businessType,
        approvalType: mapping.businessType,
        businessModule: formData.moduleName,
        businessId: `WECOM-${spNo}`,
        businessNo: spNo,
        title: detail.sp_name || mapping.businessLabel,
        applicantId: localApplicantId,
        applicantName: localApplicantName,
        deptId: localDepartmentId,
        deptName: localDepartmentName,
        amount: Number.isFinite(amount) ? amount : undefined,
        formData,
        ccUserIds: [],
      })
      record.localInstanceId = submitted.instance.id
    }
    if (status !== 'UNKNOWN') {
      const localStatus = status === 'CANCELED' ? 'REVOKED' : status
      await approvalStore.applyExternalStatus(record.localInstanceId, localStatus, '企业微信', spNo, formData)
    }
  }

  record.message = existingRecord ? '企业微信状态及详情已更新' : '已从企业微信创建审批中心单据'
  value.records = [record, ...value.records.filter(item => item.spNo !== spNo)].slice(0, 500)
  save(value)
  return { record, created: !existingRecord }
}

async function performRangeSync(startTime: number, endTime: number) {
  const stats = emptyStats()
  const maxWindowSeconds = 30 * 24 * 60 * 60
  try {
    for (let windowStart = startTime; windowStart < endTime; windowStart += maxWindowSeconds) {
      const windowEnd = Math.min(endTime, windowStart + maxWindowSeconds)
      const currentState = state()
      let cursor = currentState.sync.windowStart === windowStart ? currentState.sync.cursor : ''
      do {
        const cursorState = state()
        cursorState.sync.windowStart = windowStart
        cursorState.sync.cursor = cursor
        save(cursorState)
        const response = await requestWecom('/cgi-bin/oa/getapprovalinfo', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ starttime: windowStart, endtime: windowEnd, new_cursor: cursor, size: 100 }),
        })
        const spNos = (response.sp_no_list || []).map(String).filter(Boolean)
        stats.scanned += spNos.length
        for (const spNo of spNos) {
          try {
            const synced = await syncOneApproval(spNo)
            if (synced.created)
              stats.created++
            else
              stats.updated++
          }
          catch (error: any) {
            stats.failed++
            stats.errors.push(`${spNo}: ${error?.message || '同步失败'}`)
          }
        }
        const nextCursor = String(response.new_next_cursor || response.next_cursor || '')
        cursor = nextCursor && nextCursor !== cursor ? nextCursor : ''
      } while (cursor)
      const completedState = state()
      completedState.sync.cursor = ''
      completedState.sync.windowStart = undefined
      completedState.sync.lastWindowEnd = windowEnd
      save(completedState)
    }
    const successState = state()
    successState.sync.lastSuccessAt = new Date().toISOString()
    successState.sync.lastError = undefined
    save(successState)
  }
  catch (error: any) {
    const errorState = state()
    errorState.sync.lastError = error?.message || '批量同步失败'
    save(errorState)
    throw error
  }
  finally {
    stats.errors = stats.errors.slice(0, 20)
    const finalState = state()
    finalState.sync.lastStats = stats
    save(finalState)
  }
  return stats
}

export const wecomApprovalStore = {
  getOverview() {
    const value = state()
    return { config: publicConfig(value.config), mappings: value.mappings, records: value.records.slice(0, 100), sync: value.sync }
  },

  saveConfig(input: Partial<WecomApprovalConfig>) {
    const value = state()
    value.config = {
      ...value.config,
      ...input,
      corpSecret: input.corpSecret?.includes('*') ? value.config.corpSecret : String(input.corpSecret ?? value.config.corpSecret),
      callbackToken: input.callbackToken?.includes('*') ? value.config.callbackToken : String(input.callbackToken ?? value.config.callbackToken),
      callbackAesKey: input.callbackAesKey?.includes('*') ? value.config.callbackAesKey : String(input.callbackAesKey ?? value.config.callbackAesKey),
    }
    save(value)
    accessToken = ''
    return publicConfig(value.config)
  },

  async testConnection() {
    const config = state().config
    if (!config.corpId || !config.corpSecret)
      throw new Error('请先填写企业 ID 和审批应用 Secret')
    const url = new URL('https://qyapi.weixin.qq.com/cgi-bin/gettoken')
    url.searchParams.set('corpid', config.corpId)
    url.searchParams.set('corpsecret', config.corpSecret)
    let response: Response
    try {
      response = await fetch(url, { signal: AbortSignal.timeout(10_000) })
    }
    catch (error: any) {
      if (error?.name === 'TimeoutError')
        throw new Error('企业微信接口响应超时，请稍后重试')
      throw new Error('无法连接企业微信接口，请检查服务器网络')
    }
    let result: any
    try {
      result = await response.json()
    }
    catch {
      throw new Error(`企业微信接口返回异常 (${response.status})`)
    }
    if (!response.ok || result.errcode)
      throw new Error(result.errmsg || `企业微信连接失败 (${result.errcode || response.status})`)
    accessToken = result.access_token
    accessTokenExpiresAt = Date.now() + Math.max(60, Number(result.expires_in || 7200) - 300) * 1000
    return true
  },

  saveMapping(input: Omit<WecomTemplateMapping, 'id' | 'updatedAt'> & { id?: string }) {
    if (!input.businessType || !input.templateId)
      throw new Error('业务类型和企业微信模板 ID 不能为空')
    const catalog = APPROVAL_BUSINESS_MAP.get(input.businessType)
    if (!catalog)
      throw new Error('业务类型必须从审批中心业务目录中选择')
    const value = state()
    const mapping: WecomTemplateMapping = { ...input, direction: requiredWecomDirection(input.businessType), businessLabel: catalog.label, id: input.id || `WCM-${Date.now()}`, updatedAt: new Date().toISOString() }
    const index = value.mappings.findIndex(item => item.id === mapping.id)
    if (index >= 0)
      value.mappings[index] = mapping
    else
      value.mappings.unshift(mapping)
    save(value)
    return mapping
  },

  removeMapping(id: string) {
    const value = state()
    value.mappings = value.mappings.filter(item => item.id !== id)
    save(value)
  },

  async syncApproval(spNo: string, localInstanceId?: string) {
    return (await syncOneApproval(spNo, localInstanceId)).record
  },

  async syncRange(input: { startTime?: number, endTime?: number, days?: number } = {}) {
    if (rangeSyncPromise)
      return rangeSyncPromise
    const endTime = Math.floor(Number(input.endTime || Date.now() / 1000))
    const days = Math.min(90, Math.max(1, Number(input.days || 1)))
    const startTime = Math.floor(Number(input.startTime || endTime - days * 24 * 60 * 60))
    rangeSyncPromise = performRangeSync(startTime, endTime).finally(() => {
      rangeSyncPromise = undefined
    })
    return rangeSyncPromise
  },

  async syncIncremental() {
    const value = state()
    if (!value.config.enabled)
      return emptyStats()
    const endTime = Math.floor(Date.now() / 1000)
    const startTime = value.sync.lastWindowEnd
      ? Math.max(value.sync.lastWindowEnd - 10 * 60, endTime - 24 * 60 * 60)
      : endTime - 90 * 24 * 60 * 60
    return this.syncRange({ startTime, endTime })
  },

  async pushApproval(localInstanceId: string) {
    const value = state()
    if (!value.config.enabled)
      throw new Error('请先启用企业微信审批同步')
    const detail = await approvalStore.getDetail(localInstanceId)
    const instance = detail.instance
    if (approvalInitiationSource(instance.businessType) === 'WECOM')
      throw new Error('该人事事项必须在企业微信发起，不能从管理系统重复推送')
    const systemUsers = await systemStore.listUsers({ status: 'enabled' })
    const applicant = systemUsers.find(item => String(item.id) === String(instance.applicantId))
    const creatorUserId = applicant?.wecomUserId || value.config.initiatorUserId
    if (!creatorUserId)
      throw new Error('申请人尚未绑定企业微信 UserID')
    const mapping = value.mappings.find(item => item.enabled && item.businessType === instance.businessType && item.direction === 'CENTER_TO_WECOM')
    if (!mapping)
      throw new Error('当前业务类型尚未配置可推送的企业微信模板')

    const contents: any[] = []
    if (mapping.titleControlId) {
      contents.push({ control: 'Text', id: mapping.titleControlId, value: { text: instance.title } })
    }
    if (mapping.amountControlId && instance.amount != null) {
      contents.push({ control: 'Money', id: mapping.amountControlId, value: { new_money: String(Math.round(Number(instance.amount) * 100)) } })
    }
    const processNodes = detail.nodes.map((node: any) => {
      const userIds = (node.approverIds || []).map((id: string | number) => systemUsers.find(user => String(user.id) === String(id))?.wecomUserId).filter(Boolean)
      if (!userIds.length && value.config.approverUserId)
        userIds.push(value.config.approverUserId)
      if (!userIds.length)
        throw new Error(`审批节点“${node.name}”的审批人尚未绑定企业微信 UserID`)
      return { type: 1, apv_rel: 1, userid: userIds }
    })
    const result = await requestWecom('/cgi-bin/oa/applyevent', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        creator_userid: creatorUserId,
        template_id: mapping.templateId,
        use_template_approver: 0,
        process: {
          node_list: processNodes,
        },
        apply_data: { contents },
        summary_list: [{ summary_info: [{ text: instance.title, lang: 'zh_CN' }] }],
      }),
    })
    const spNo = String(result.sp_no || '')
    if (!spNo)
      throw new Error('企业微信未返回审批单号')
    const record: WecomSyncRecord = {
      id: `WCS-${spNo}`,
      spNo,
      localInstanceId,
      templateId: mapping.templateId,
      title: instance.title,
      applicantName: instance.applicantName,
      status: 'PENDING',
      source: 'APPROVAL_CENTER',
      lastSyncedAt: new Date().toISOString(),
      message: '已从审批中心发起企业微信审批',
    }
    value.records = [record, ...value.records.filter(item => item.localInstanceId !== localInstanceId)].slice(0, 200)
    save(value)
    return record
  },

  archiveLocalRecord(localInstanceId: string, reason?: string) {
    const value = state()
    const record = value.records.find(item => item.localInstanceId === localInstanceId)
    if (!record)
      return undefined
    if (['PENDING', 'APPROVING'].includes(record.status))
      record.status = 'REVOKED'
    record.lastSyncedAt = new Date().toISOString()
    record.message = `管理系统已${record.status === 'REVOKED' ? '撤销并归档' : '作废归档'}：${reason || '管理员删除'}；企业微信保留历史记录`
    save(value)
    return record
  },

  verifySignature(signature: string, timestamp: string, nonce: string, encrypted: string) {
    const token = state().config.callbackToken
    const digest = createHash('sha1').update([token, timestamp, nonce, encrypted].sort().join('')).digest('hex')
    return Boolean(token) && digest === signature
  },

  decryptCallback(encrypted: string) {
    const config = state().config
    if (!config.callbackAesKey || !config.corpId)
      throw new Error('尚未配置回调 EncodingAESKey')
    return decryptCallback(encrypted, config.callbackAesKey, config.corpId)
  },

  async handleCallbackXml(xml: string) {
    const spNo = xmlValue(xml, 'SpNo') || xmlValue(xml, 'ApprovalNo')
    if (spNo)
      return await this.syncApproval(spNo)
    return undefined
  },

  extractEncrypted: (xml: string) => xmlValue(xml, 'Encrypt'),
}

