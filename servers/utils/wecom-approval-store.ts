const dataFile = process.env.WECOM_APPROVAL_DATA_FILE
  ? resolve(process.env.WECOM_APPROVAL_DATA_FILE)
  : resolve(process.env.UPLOAD_DIR || resolve(process.cwd(), 'uploads'), '.private', 'wecom-approval.json')
function emptyState(): WecomState {
  return {
    config: { corpId: '', corpSecret: '', callbackToken: '', callbackAesKey: '', enabled: false, initiatorUserId: '', approverUserId: '' },
    mappings: [],
    records: [],
    sync: { cursor: '' },
  }
}

let accessToken = ''
let accessTokenExpiresAt = 0

function state() {
  const value = readJsonFile(dataFile, emptyState())
  value.sync ||= { cursor: '' }
  value.mappings = value.mappings.map(mapping => APPROVAL_BUSINESS_MAP.has(mapping.businessType)
    ? { ...mapping, direction: requiredWecomDirection(mapping.businessType) }
    : mapping)
  return value
}

function save(value: WecomState) {
  writeJsonFile(dataFile, value)
}

function mask(value: string) {
  if (!value)
    return ''
  return value.length <= 8 ? '********' : `${value.slice(0, 4)}****${value.slice(-4)}`
}

function publicConfig(config: WecomApprovalConfig) {
  return {
    corpId: config.corpId,
    corpSecret: mask(config.corpSecret),
    callbackToken: mask(config.callbackToken),
    callbackAesKey: mask(config.callbackAesKey),
    hasCorpSecret: Boolean(config.corpSecret),
    hasCallbackToken: Boolean(config.callbackToken),
    hasCallbackAesKey: Boolean(config.callbackAesKey),
    enabled: config.enabled,
    initiatorUserId: config.initiatorUserId || '',
    approverUserId: config.approverUserId || '',
  }
}

async function requestWecom(path: string, init?: RequestInit) {
  const config = state().config
  if (!config.corpId || !config.corpSecret)
    throw new Error('请先填写企业 ID 和审批应用 Secret')
  if (!accessToken || Date.now() >= accessTokenExpiresAt) {
    const url = new URL('https://qyapi.weixin.qq.com/cgi-bin/gettoken')
    url.searchParams.set('corpid', config.corpId)
    url.searchParams.set('corpsecret', config.corpSecret)
    const response = await fetch(url)
    const result = await response.json() as any
    if (!response.ok || result.errcode)
      throw new Error(result.errmsg || `企业微信连接失败 (${result.errcode || response.status})`)
    accessToken = result.access_token
    accessTokenExpiresAt = Date.now() + Math.max(60, Number(result.expires_in || 7200) - 300) * 1000
  }
  const url = new URL(`https://qyapi.weixin.qq.com${path}`)
  url.searchParams.set('access_token', accessToken)
  const response = await fetch(url, init)
  const result = await response.json() as any
  if (!response.ok || result.errcode)
    throw new Error(result.errmsg || `企业微信接口调用失败 (${result.errcode || response.status})`)
  return result
}

function mapStatus(value: unknown): WecomSyncStatus {
  const status = Number(value)
  return ({ 1: 'PENDING', 2: 'APPROVED', 3: 'REJECTED', 4: 'CANCELED', 5: 'REVOKED', 6: 'APPROVING', 7: 'APPROVING', 10: 'APPROVING' } as Record<number, WecomSyncStatus>)[status] || 'UNKNOWN'
}

function toIsoTime(value: unknown, fallback = new Date().toISOString()) {
  const numeric = Number(value)
  if (!Number.isFinite(numeric) || numeric <= 0)
    return fallback
  return new Date(numeric < 1e12 ? numeric * 1000 : numeric).toISOString()
}

function emptyStats(): WecomSyncStats {
  return { scanned: 0, created: 0, updated: 0, skipped: 0, failed: 0, errors: [] }
}

function latestApprovalTime(records: any[] = []) {
  const timestamps = records.flatMap((record: any) => [
    record.sptime,
    record.sp_time,
    ...(record.details || []).flatMap((detail: any) => [detail.sptime, detail.sp_time]),
  ]).map(Number).filter(value => Number.isFinite(value) && value > 0)
  return timestamps.length ? toIsoTime(Math.max(...timestamps)) : undefined
}

function controlValue(item: any) {
  const value = item?.value ?? {}
  if (value.text != null)
    return String(value.text)
  if (value.new_money != null)
    return Number(value.new_money)
  if (value.date?.s_timestamp) {
    return new Intl.DateTimeFormat('en-CA', {
      timeZone: 'Asia/Shanghai',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).format(new Date(Number(value.date.s_timestamp) * 1000))
  }
  if (value.bank_account) {
    const account = value.bank_account
    return {
      accountType: Number(account.account_type) === 1 ? '对公账户' : '个人账户',
      accountName: String(account.account_name || ''),
      accountNumber: String(account.account_number || ''),
      bankName: String(account.bank?.bank_alias || ''),
      bankProvince: String(account.bank?.province || ''),
      bankCity: String(account.bank?.city || ''),
      bankBranchName: String(account.bank?.bank_branch_name || ''),
      remark: String(account.remark || ''),
    }
  }
  if (value.files?.length) {
    return value.files.map((file: any, index: number) => ({
      fileId: String(file.file_id || ''),
      name: String(file.file_name || file.name || `附件${index + 1}`),
    }))
  }
  if (value.selector?.options?.length)
    return value.selector.options.map((option: any) => option.value?.[0]?.text || option.key).filter(Boolean).join('、')
  if (value.children?.list?.length)
    return value.children.list.map((child: any) => controlValue(child)).filter(Boolean).join('、')
  return ''
}

function localizedTitle(item: any) {
  const titles = item?.title || []
  return String(titles.find((title: any) => title.lang === 'zh_CN')?.text || titles[0]?.text || item?.id || '')
}

function approvalFields(detail: any) {
  const items = detail.apply_data?.contents || detail.apply_data?.content || []
  return items.map((item: any) => ({ id: String(item.id || item.control_id || ''), title: localizedTitle(item), value: controlValue(item), control: item.control }))
}

function approvalContents(detail: any) {
  const result = new Map<string, any>()
  for (const field of approvalFields(detail)) {
    if (field.id)
      result.set(field.id, field.value)
  }
  return result
}

const userCache = new Map<string, { name: string, mobile: string, departmentIds: number[] }>()
const departmentCache = new Map<string, string>()

async function resolveWecomUser(userId: string) {
  if (!userId)
    return { name: '', mobile: '', departmentIds: [] as number[] }
  const cached = userCache.get(userId)
  if (cached)
    return cached
  try {
    const result = await requestWecom(`/cgi-bin/user/get?userid=${encodeURIComponent(userId)}`)
    const user = {
      name: String(result.name || userId),
      mobile: String(result.mobile || ''),
      departmentIds: (result.department || []).map(Number).filter(Number.isFinite),
    }
    userCache.set(userId, user)
    return user
  }
  catch {
    return { name: userId, mobile: '', departmentIds: [] as number[] }
  }
}

async function resolveDepartmentName(departmentId: string | number | undefined) {
  const id = String(departmentId || '')
  if (!id)
    return ''
  if (departmentCache.has(id))
    return departmentCache.get(id) || ''
  try {
    const result = await requestWecom(`/cgi-bin/department/get?id=${encodeURIComponent(id)}`)
    const name = String(result.department?.name || '')
    departmentCache.set(id, name)
    return name
  }
  catch {
    return ''
  }
}

async function enrichApprovalFlow(records: any[] = []) {
  return Promise.all(records.map(async (record: any) => ({
    status: mapStatus(record.sp_status),
    approvers: await Promise.all((record.details || []).map(async (detail: any) => ({
      userId: detail.approver?.userid,
      name: (await resolveWecomUser(String(detail.approver?.userid || ''))).name,
      status: mapStatus(detail.sp_status),
      actedAt: detail.sptime ? toIsoTime(detail.sptime) : undefined,
      comment: detail.speech || '',
    }))),
  })))
}

function resolveBusinessDomain(departmentName: string) {
  if (/酒店|宾馆/.test(departmentName))
    return '酒店'
  if (/运输|车队|物流/.test(departmentName))
    return '运输'
  if (/贸易|商贸/.test(departmentName))
    return '贸易'
  return '公司'
}

function xmlValue(xml: string, name: string) {
  const match = xml.match(new RegExp(`<${name}>(?:<!\\[CDATA\\[)?([\\s\\S]*?)(?:\\]\\]>)?</${name}>`, 'i'))
  return match?.[1]?.trim() || ''
}

function decryptCallback(encrypted: string, aesKey: string, corpId: string) {
  const key = Buffer.from(`${aesKey}=`, 'base64')
  const decipher = createDecipheriv('aes-256-cbc', key, key.subarray(0, 16))
  decipher.setAutoPadding(false)
  const decoded = Buffer.concat([decipher.update(encrypted, 'base64'), decipher.final()])
  const pad = decoded[decoded.length - 1]
  const plain = decoded.subarray(0, decoded.length - pad)
  const messageLength = plain.readUInt32BE(16)
  const message = plain.subarray(20, 20 + messageLength).toString('utf8')
  const receiver = plain.subarray(20 + messageLength).toString('utf8')
  if (receiver !== corpId)
    throw new Error('回调企业 ID 不匹配')
  return message
}

